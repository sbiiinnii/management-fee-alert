#!/bin/bash

TODAY=$(date +%d)
TODAY=$((10#$TODAY))

echo ""
echo "=============================================="

if [ "$TODAY" -eq 22 ]; then
    echo "오늘은 관리비 납부일입니다!"
    echo "집주인에게 관리비를 입금했는지 확인하세요."
elif [ "$TODAY" -ge 19 ] && ["$TODAY" -lt 22 ]; then
    echo "관리비 납부일이 다가오고 있습니다."
    echo "매월 22일까지 관리비를 입금하세요."
else
   echo "관리비 알림: 오늘은 납부일이 아닙니다."
fi

echo "=============================================="
echo ""
